export function isAuthoredTextAuthor(
  value: unknown,
): value is AuthoredTextAuthor {
  return (
    typeof value === "string" &&
    (AUTHORED_TEXT_AUTHORS as readonly string[]).includes(value)
  );
}

export function normalizeAuthorshipHighlightMode(
  value: unknown,
): AuthorshipHighlightMode {
  return typeof value === "string" &&
    (AUTHORSHIP_HIGHLIGHT_MODES as readonly string[]).includes(value)
    ? (value as AuthorshipHighlightMode)
    : "subtle";
}

export function normalizeAuthoredTextAuthor(
  value: unknown,
  fallback: AuthoredTextAuthor = "human",
): AuthoredTextAuthor {
  return isAuthoredTextAuthor(value) ? value : fallback;
}

export function normalizeAuthoredNarrativeBlock(
  block: AuthoredNarrativeBlock,
  fallbackAuthor: AuthoredTextAuthor = "human",
): NormalizedAuthoredNarrativeBlock {
  const sources = block.sources ?? [];
  const sourceRef = sources[0]?.ref;

  return {
    id:
      block.id?.trim() ||
      `legacy-${normalizeAuthoredTextAuthor(block.author, fallbackAuthor)}-${block.content.slice(0, 24)}`,
    content: block.content,
    author: normalizeAuthoredTextAuthor(block.author, fallbackAuthor),
    authorAgentVersion: block.author_agent_version ?? undefined,
    confidence:
      typeof block.confidence === "number" ? block.confidence : undefined,
    reviewedByHuman: Boolean(block.reviewed_by_human),
    sourceRef,
    sources,
    timestamp: block.timestamp ?? undefined,
  };
}

export function excerptText(text: string, maxLength = 132) {
  const compact = text.replace(/\s+/gu, " ").trim();
  if (compact.length <= maxLength) {
    return compact;
  }
  return `${compact.slice(0, maxLength - 1).trimEnd()}…`;
}

export function extractTextFromNode(node: ReactNode): string {
  if (typeof node === "string" || typeof node === "number") {
    return String(node);
  }

  if (Array.isArray(node)) {
    return node.map((item) => extractTextFromNode(item)).join(" ");
  }

  if (!node) {
    return "";
  }

  if (isValidElement<{ children?: ReactNode }>(node)) {
    return extractTextFromNode(node.props.children ?? null);
  }

  return Children.toArray(node)
    .map((item) => extractTextFromNode(item))
    .join(" ");
}
