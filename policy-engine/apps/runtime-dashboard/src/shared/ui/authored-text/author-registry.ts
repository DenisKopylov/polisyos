import { Children, isValidElement, type ReactNode } from "react";

import { GLYPH_ANCHORS } from "@/shared/brand/glyph-vocabulary";

export const AUTHORED_TEXT_AUTHORS = [
  "citation",
  "human",
  "drafter",
  "formalizer",
  "critic",
] as const;

export type AuthoredTextAuthor = (typeof AUTHORED_TEXT_AUTHORS)[number];

export const AUTHORSHIP_HIGHLIGHT_MODES = [
  "off",
  "subtle",
  "prominent",
] as const;

export type AuthorshipHighlightMode =
  (typeof AUTHORSHIP_HIGHLIGHT_MODES)[number];

export type AuthorshipSource = {
  kind?: string;
  ref: string;
};

export type AuthoredNarrativeBlock = {
  id?: string;
  content: string;
  author?: AuthoredTextAuthor | null;
  author_agent_version?: string | null;
  sources?: AuthorshipSource[] | null;
  timestamp?: string | null;
  confidence?: number | null;
  reviewed_by_human?: boolean | null;
};

export type NormalizedAuthoredNarrativeBlock = {
  id: string;
  content: string;
  author: AuthoredTextAuthor;
  authorAgentVersion?: string;
  sourceRef?: string;
  sources: AuthorshipSource[];
  timestamp?: string;
  confidence?: number;
  reviewedByHuman: boolean;
};

export type AuthorRegistryEntry = {
  badgeLabel: string;
  borderVar: `--${string}`;
  glyph?: string;
  toneClassName: string;
  announcement: (sourceRef?: string) => string;
};

const CITATION_LABEL = "Citation";
const HUMAN_LABEL = "Operator";
const DRAFTER_LABEL = "Drafter";
const FORMALIZER_LABEL = "Formalizer";
const CRITIC_LABEL = "Critic";
const QUOTED_TEXT_PREFIX = "Quoted text from";
const AI_GENERATED_PREFIX = "AI-generated by";
const AI_REVIEW_PREFIX = "AI review by";

