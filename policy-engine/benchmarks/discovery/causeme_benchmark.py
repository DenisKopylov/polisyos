@dataclasses.dataclass
class DiscoveryResult:
    dgp_name: str
    auroc: float
    f1: float
    n_true_edges: int
    n_pred_edges: int
    n_vars: int


# ---------------------------------------------------------------------------
# BenchmarkCase builder
# ---------------------------------------------------------------------------


def _causeme_case(
    dgp: VarDGP,
    *,
    T: int,
    seed: int,
    auroc_threshold: float,
    f1_threshold: float,
    lag: int = 1,
) -> BenchmarkCase:
    def runner() -> DiscoveryResult:
        data = _simulate_var1(dgp, T, seed)
        scores, pred_adj = discover_var_granger(data, lag=lag)

        n = dgp.n_vars
        true_flat = dgp.true_adj.flatten()
        # Exclude diagonal
        mask = np.ones(n * n, dtype=bool)
        mask[np.arange(n) * n + np.arange(n)] = False

        auroc = _compute_auroc(scores.flatten()[mask], true_flat[mask])
        f1 = _compute_f1(pred_adj.flatten()[mask], true_flat[mask])

        return DiscoveryResult(
            dgp_name=dgp.name,
            auroc=auroc,
            f1=f1,
            n_true_edges=int(dgp.true_adj.sum()),
            n_pred_edges=int(pred_adj.sum()),
            n_vars=n,
        )

    def checker(r: DiscoveryResult) -> bool:
        issues = []
        if r.auroc < auroc_threshold:
            issues.append(f"AUROC={r.auroc:.3f} < {auroc_threshold}")
        if r.f1 < f1_threshold:
            issues.append(f"F1={r.f1:.3f} < {f1_threshold}")
        if issues:
            raise AssertionError(f"{dgp.name}: " + "; ".join(issues))
        return True

    return BenchmarkCase(
        name=f"causeme::{dgp.name}",
        circuit=CIRCUIT,
        runner=runner,
        checker=checker,
        tags=("causeme", "granger", dgp.name),
        timeout_s=60.0,
    )


# ---------------------------------------------------------------------------
# Harness builder
# ---------------------------------------------------------------------------


def build_causeme_harness(
    *,
    T: int = 500,
    seed: int = 42,
    auroc_threshold: float = 0.75,
    f1_threshold: float = 0.45,
) -> BenchmarkHarness:
    harness = BenchmarkHarness()
    for dgp in _make_var_dgps():
        case = _causeme_case(
            dgp,
            T=T,
            seed=seed,
            auroc_threshold=auroc_threshold,
            f1_threshold=f1_threshold,
        )
        harness.register(case)
    return harness


