"""Circuit 3: Discovery — CauseMe-style time-series benchmark.

Evaluates skeleton + orientation recovery from multivariate time-series data
generated by Vector Autoregression (VAR) models with known ground-truth
causal structure.  Mirrors the evaluation protocol of the CauseMe platform
(Runge et al. 2019).

DGPs
----
- 5 synthetic VAR(1) DGPs with 3–6 variables (chain, fork, collider, complex)
- T = 500 time steps, standard Gaussian innovations

Algorithm
---------
Lag-1 Granger causality via F-test (pure numpy, no scipy required).
Score per directed pair: 1 − p-value (higher = more evidence for edge).

Metrics
-------
AUROC on directed edge recovery
F1 at α = 0.05 threshold

Bar
---
AUROC ≥ 0.75  (top-quartile reference on CauseMe platform)
F1   ≥ 0.45

Usage
-----
    python benchmarks/discovery/causeme_benchmark.py
    python benchmarks/discovery/causeme_benchmark.py --json report.json
"""

