def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Circuit 3 — CauseMe time-series discovery benchmark")
    parser.add_argument("--T", type=int, default=500, help="Time series length")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--auroc-threshold", type=float, default=0.75)
    parser.add_argument("--f1-threshold", type=float, default=0.45)
    parser.add_argument("--mode", choices=("smoke", "acceptance"))
    parser.add_argument("--json", metavar="FILE")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)
    mode = resolve_mode(args.mode).value
    preflight = build_preflight(mode=mode, data_source="synthetic_var_ground_truth")
    print_preflight(preflight)

    harness = build_causeme_harness(
        T=args.T,
        seed=args.seed,
        auroc_threshold=args.auroc_threshold,
        f1_threshold=args.f1_threshold,
    )
    report = harness.run(circuit=CIRCUIT)
    harness.print_report(report, verbose=not args.quiet)

    if args.json:
        Path(args.json).write_text(
            json.dumps(_report_to_dict(report, mode=mode, preflight=preflight), indent=2), encoding="utf-8"
        )
        print(f"\nJSON report written to: {args.json}")

    return 1 if report.n_total() - report.n_passed() > 0 else 0


if __name__ == "__main__":
    sys.exit(main())
