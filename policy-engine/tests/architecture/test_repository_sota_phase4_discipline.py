def test_phase4_generated_artifact_registry_covers_non_python_surfaces() -> None:
    families = _families_by_id()

    required = {
        "runtime-openapi-snapshot",
        "runtime-api-client",
        "runtime-dashboard-api-types",
        "release-sbom",
        "frontend-workspace-lockfiles",
        "frontend-local-generated-outputs",
        "committed-data-fixtures-and-catalogs",
        "local-medallion-data-lake",
        "local-runtime-state",
        "ops-observability-baselines",
        "ops-security-release-baselines",
        "ops-runtime-and-migration-baselines",
    }
    assert required <= set(families)

    for family_id in required:
        family = families[family_id]
        assert family["owner"], family_id
        assert family["approval_owner"], family_id
        assert family["source_of_truth"], family_id
        assert family["outputs"], family_id
        assert family["regenerate_commands"], family_id
        assert family["freshness_rule"], family_id
        assert family["commit_policy"] in {"committed", "mixed", "local_ignored"}
        assert family["drift_gate"] in {"automated", "manual_review", "ignored_by_policy"}
        assert _contract_path_exists(family["workflow"]), family_id

    for family in families.values():
        if family["commit_policy"] != "committed":
            continue
        missing = [output for output in family["outputs"] if not _contract_path_exists(output)]
        assert missing == []

    assert (
        (REPO_ROOT / "frontend/runtime-api-client/runtimeApiClient.ts")
        .read_text(encoding="utf-8")
        .startswith("// GENERATED FILE. DO NOT EDIT.")
    )
    assert (
        (REPO_ROOT / "frontend/runtime-api-client/runtimeApiClient.js")
        .read_text(encoding="utf-8")
        .startswith("// GENERATED FILE. DO NOT EDIT.")
    )
    assert "auto-generated by openapi-typescript" in (
        REPO_ROOT / "frontend/runtime-dashboard/src/api/types.ts"
    ).read_text(encoding="utf-8")


def test_phase4_frontend_workspace_contract_has_owners_commands_and_ignores() -> None:
    contract = _read_toml("architecture/frontend_workspaces.toml")
    workspaces = {workspace["id"]: workspace for workspace in contract["workspace"]}

    assert set(workspaces) == {
        "cli",
        "runtime-api-client",
        "runtime-dashboard",
        "runtime-reference-shell",
    }

    for workspace in workspaces.values():
        root = REPO_ROOT / workspace["path"]
        package_json = _contract_path(workspace["package_json"])
        lockfile = _contract_path(workspace["lockfile"])
        scripts = json.loads(package_json.read_text(encoding="utf-8"))["scripts"]

        assert root.exists()
        assert workspace["owner"]
        assert package_json.exists()
        assert lockfile.exists()
        assert workspace["public_entrypoints"]

        for command in (
            workspace["build_commands"] + workspace["test_commands"] + workspace["drift_commands"]
        ):
            script = _npm_script_name(command)
            if script is not None:
                assert script in scripts, (workspace["id"], command)

        for output in workspace["generated_outputs"]:
            assert (root / output).exists(), (workspace["id"], output)

        for output in workspace["ignored_outputs"]:
            sample = _ignored_output_sample(root, output)
            assert _git_ignores(sample), sample


def test_phase4_data_policy_keeps_local_lake_ignored_and_product_data_allowlisted() -> None:
    policy = _read_toml("architecture/data_policy.toml")

    assert policy["data_policy"]["local_data_lake"] == "data/policy-engine-local"
    assert policy["data_policy"]["product_commit_policy"] == "allowlist_only"
    assert policy["data_policy"]["cleanup_commands"]
    assert _git_ignores(REPO_ROOT / "data" / "bronze" / "phase4.tmp")

    for zone in policy["medallion_zone"]:
        assert zone["state"] == "ignored_local"
        assert zone["cleanup_command"]
        assert _git_ignores(_contract_path(zone["path"]) / "phase4.tmp")

    committed_patterns: list[str] = ["data/README.md"]
    for item in policy["product_data_class"]:
        if item["commit_policy"].startswith("committed"):
            committed_patterns.extend(item["allowed_patterns"])
        else:
            for local_path in item["paths"]:
                assert _git_ignores(REPO_ROOT / local_path / "phase4.tmp")

    tracked_data = subprocess.run(
        ["git", "ls-files", "policy-engine/data"],
        cwd=WORKSPACE_ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.splitlines()
    max_bytes = int(policy["data_policy"]["max_committed_example_bytes"])

    for tracked in tracked_data:
        relative = Path(tracked).relative_to("policy-engine").as_posix()
        assert any(fnmatch.fnmatch(relative, pattern) for pattern in committed_patterns), relative
        path = WORKSPACE_ROOT / tracked
        assert path.stat().st_size <= max_bytes, relative


