def _read_toml(path: str) -> dict[str, Any]:
    return tomllib.loads((REPO_ROOT / path).read_text(encoding="utf-8"))


def _families_by_id() -> dict[str, dict[str, Any]]:
    data = _read_toml("architecture/generated_artifacts.toml")
    return {family["id"]: family for family in data["family"]}


def _contract_path(path: str) -> Path:
    candidate = Path(path)
    if candidate.is_absolute():
        return candidate
    return (REPO_ROOT / candidate).resolve()


def _contract_path_exists(path: str) -> bool:
    return _contract_path(path).exists()


def _baseline_path_exists(path: str) -> bool:
    resolved = _contract_path(path)
    if any(char in path for char in "*?["):
        return bool(list(resolved.parent.glob(resolved.name)))
    return resolved.exists()


def _npm_script_name(command: str) -> str | None:
    if command == "npm test":
        return "test"
    if command.startswith("npm run "):
        return command.removeprefix("npm run ").split()[0]
    return None


def _ignored_output_sample(root: Path, output: str) -> Path:
    if output.endswith("/"):
        return root / output / "phase4.tmp"
    return root / output


def _git_ignores(path: Path) -> bool:
    result = subprocess.run(
        ["git", "check-ignore", "-q", path.resolve().relative_to(WORKSPACE_ROOT).as_posix()],
        cwd=WORKSPACE_ROOT,
        check=False,
    )
    return result.returncode == 0
