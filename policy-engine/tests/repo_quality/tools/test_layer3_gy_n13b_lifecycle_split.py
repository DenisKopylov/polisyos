@pytest.mark.parametrize("receipt_kind", ["lifecycle", "contract"])
def test_previous_epoch_is_readable_but_cannot_enter_current_admission(
    tmp_path: Path, receipt_kind: str
) -> None:
    path = (
        owner.DEFAULT_N13B_LIFECYCLE_MANIFEST
        if receipt_kind == "lifecycle"
        else owner.DEFAULT_N13B_CONTRACT
    )
    payload = json.loads((REPO_ROOT / path).read_bytes())
    lifecycle = payload if receipt_kind == "lifecycle" else payload["lifecycle"]
    if lifecycle["schema_version"] != "policyos.layer3.gy.n13b.lifecycle_manifest.v2":
        current = owner.N13bLifecycleManifest.model_validate(lifecycle)
        historical = owner.N13bLifecycleManifestV2.model_construct(
            **{
                name: getattr(current, name)
                for name in owner.N13bLifecycleManifestV2.model_fields
                if name != "schema_version"
            },
        )
        historical = historical.model_copy(
            update={"manifest_sha256": owner.content_sha256(historical.identity_payload())}
        )
        if receipt_kind == "lifecycle":
            payload = historical.model_dump(mode="json")
        else:
            current_contract = owner.N13bAcquisitionExecutorContract.model_validate(payload)
            old_contract = owner.N13bAcquisitionExecutorContractV4.model_construct(
                **{
                    name: getattr(current_contract, name)
                    for name in owner.N13bAcquisitionExecutorContractV4.model_fields
                    if name not in {"schema_version", "lifecycle"}
                },
                lifecycle=historical,
            )
            old_contract = old_contract.model_copy(
                update={"contract_sha256": owner.content_sha256(old_contract.identity_payload())}
            )
            payload = old_contract.model_dump(mode="json")
    current_model = (
        owner.N13bLifecycleManifest
        if receipt_kind == "lifecycle"
        else owner.N13bAcquisitionExecutorContract
    )

    with pytest.raises(ValidationError):
        current_model.model_validate(payload)

    historical_path = tmp_path / f"{receipt_kind}.json"
    historical_path.write_text(json.dumps(payload))
    reader = (
        owner.read_n13b_lifecycle_manifest
        if receipt_kind == "lifecycle"
        else owner.read_n13b_acquisition_executor_contract
    )
    historical = reader(historical_path)
    assert historical.model_dump(mode="json") == payload
