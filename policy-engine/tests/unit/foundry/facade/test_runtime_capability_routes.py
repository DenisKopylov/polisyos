def test_runtime_consumers_use_exact_admitted_foundry_facades() -> None:
    source_root = Path(__file__).resolve().parents[4] / "src"
    expected_by_file: dict[str, Counter[tuple[str, str]]] = {}
    for source_path, facade, name, count in _ROUTE_BINDINGS:
        expected_by_file.setdefault(source_path, Counter())[(facade, name)] += count

    for source_path, expected in expected_by_file.items():
        tree = ast.parse((source_root / source_path).read_text())
        selected_names = {name for _, name in expected}
        actual = Counter(
            (node.module, alias.name)
            for node in ast.walk(tree)
            if isinstance(node, ast.ImportFrom)
            for alias in node.names
            if alias.name in selected_names
        )
        assert actual == expected, source_path


def test_foundry_facade_exports_preserve_canonical_owner_identity() -> None:
    for facade_module, name, owner_module, owner_name in _OWNER_IDENTITIES:
        facade_value = getattr(import_module(facade_module), name)
        owner_value = getattr(import_module(owner_module), owner_name)
        assert facade_value is owner_value, (
            facade_module,
            name,
            owner_module,
            owner_name,
        )


def test_missing_methods_facade_route_fails_closed(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    methods = import_module("polisyos.foundry.methods")
    methods_api = import_module("polisyos.foundry.methods.api")
    name = "BootstrapExecutionWork"
    monkeypatch.delitem(methods_api._EXPORTS, name)
    monkeypatch.delitem(methods_api.__dict__, name, raising=False)
    monkeypatch.delitem(methods.__dict__, name, raising=False)

    with pytest.raises(AttributeError, match="BootstrapExecutionWork"):
        getattr(methods, name)
